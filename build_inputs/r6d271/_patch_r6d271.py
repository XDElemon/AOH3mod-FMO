def patch_file(p, pairs):
    s = open(p, encoding='utf-8').read()
    for i, (old, new) in enumerate(pairs):
        c = s.count(old)
        assert c == 1, ('anchor-miss', p, i, c)
        s = s.replace(old, new, 1)
    open(p, 'w', encoding='utf-8').write(s)

