def patch_menu_manager():
    path = os.path.join(SMALI, "aoc/kingdoms/lukasz/menu/MenuManager.smali")
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")

    cleaned, skip = [], False
    for ln in lines:
        s = ln.strip()
        if s.startswith(MARK_BEGIN):
            skip = True
            continue
        if s.startswith(MARK_END):
            skip = False
            continue
        if not skip:
            cleaned.append(ln)
    lines = cleaned

    method_idx = next((i for i, ln in enumerate(lines)
                       if ln.startswith(".method public final rebuildInGame_Event(")), None)
    if method_idx is None:
        raise SystemExit("❌ MenuManager 里找不到 rebuildInGame_Event")

    sig = ("invoke-", "new-instance", "iget", "iput", "sget", "sput", "const",
           "move", "return", "if-", "goto", "aget", "aput", "check-cast",
           "add-int", "sub-int", "mul-int", "div-int", "and-int", "or-int", "cmp")
    insert_at, seen_regs = None, False
    for i in range(method_idx, len(lines)):
        ln = lines[i].strip()
        if ln.startswith(".registers") or ln.startswith(".locals"):
            seen_regs = True
            continue
        if not seen_regs:
            continue
        if not ln or ln.startswith(".param") or ln.startswith(".line") or ln.startswith("#"):
            continue
        if ln.startswith(".local") or ln.startswith(".end local"):
            continue
        if ln.startswith(sig):
            insert_at = i
            break
    if insert_at is None:
        raise SystemExit("❌ 定位插入点失败")

    hook = HOOK_BODY.format(begin=MARK_BEGIN, end=MARK_END).split("\n")
    lines[insert_at:insert_at] = hook

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("  ✅ 已注入钩子: MenuManager.rebuildInGame_Event")


